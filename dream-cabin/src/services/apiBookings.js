const getAllBookings = async () => {
  return await getData(BOOKINGS + PERFORM_GET_ALL);
};

const getBookingById = async (id) => {
  return await getData(BOOKINGS + PERFORM_GET_BY_ID(id));
};
const createBooking = async (obj) => {
  const url = BOOKINGS + PERFORM_CREATE;
  return await createData({ url, obj });
};
const updateBookingStatus = async ({ id, status }) => {
  const url = BOOKINGS + PERFORM_UPDATE_BY_ID(id) + STATUS;
  return await updateData({ url, obj: { status, id } });
};

export { getAllBookings, getBookingById, createBooking, updateBookingStatus };
